-- ÉTAPE 2 · La table de recherche des traces, créée elle aussi par l'exporteur
--  Une interface de tracing demande d'abord "quand cette trace a-t-elle eu lieu ?". Cette
--  petite table, triée par TraceId, garde le premier et le dernier horodatage de chaque
--  trace ; sa vue la remplit à chaque insertion dans otel_traces. La vraie requête ne lit
--  ensuite qu'une fenêtre de temps étroite (module 7).
CREATE OR REPLACE TABLE payflow_otel.otel_traces_trace_id_ts
(
    TraceId  String CODEC(ZSTD(1)),
    Start    DateTime CODEC(Delta, ZSTD(1)),
    End      DateTime CODEC(Delta, ZSTD(1)),
    INDEX idx_trace_id TraceId TYPE bloom_filter(0.01) GRANULARITY 1
)
ENGINE = MergeTree
PARTITION BY toDate(Start)
ORDER BY (TraceId, Start)
TTL toDate(Start) + toIntervalYear(3);

CREATE OR REPLACE MATERIALIZED VIEW payflow_otel.otel_traces_trace_id_ts_mv TO payflow_otel.otel_traces_trace_id_ts AS
SELECT TraceId, min(Timestamp) AS Start, max(Timestamp) AS End
FROM payflow_otel.otel_traces
WHERE TraceId != ''
GROUP BY TraceId;


